#!/usr/bin/env node
// Write references/index.mjs from references/*.md and SKILL.md, so hosts without a file system (the
// backend on Cloudflare) can serve the same text: REFERENCES (each note by name), SKILL_CONFIG
// (SKILL.md from "## Config" up to "## Environment" — the config grammar, which does not depend on
// how the scripts are run — without its "### Detail pages" subsection and the stop reasons only the CLI process
// writes), SKILL_CONFIG_DETAIL (that subsection, for hosts that offer detail pages) and REFERENCES_HOST (the notes
// for a host that runs the collector in-process, without the CLI's `--resume`). Run after editing either; a test
// checks they match.
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..')
const dir = path.join(root, 'references')
const names = fs
  .readdirSync(dir)
  .filter(f => f.endsWith('.md'))
  .sort()
const notes = Object.fromEntries(names.map(f => [f.replace(/\.md$/, ''), fs.readFileSync(path.join(dir, f), 'utf8')]))
const entriesOf = byName => Object.entries(byName).map(([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`)

// Going on after a stop with `--resume` (rerun the same command, same --out) is the CLI's: a host that runs the
// collector in-process has no such command, and the text would send its agent after one. REFERENCES_HOST leaves it
// out of stop-signals; the CLI reads the .md files as written.
const stopSignals = notes['stop-signals']
const resumeCell = ', or go on: `--resume` with a higher limit'
const resumeHeading = '\n## Going on after a stop: `--resume`\n'
if (stopSignals?.split(resumeCell).length !== 2) throw new Error(`stop-signals.md's max-pages / max-rows row must end its check with "${resumeCell}" once`)
const resumeStart = stopSignals.indexOf(resumeHeading)
const resumeEnd = stopSignals.indexOf('\n## ', resumeStart + 1)
if (resumeStart < 0 || resumeEnd < 0) throw new Error('stop-signals.md needs a "## Going on after a stop: `--resume`" section followed by another "## " section')
const hostNotes = { ...notes, 'stop-signals': (stopSignals.slice(0, resumeStart) + stopSignals.slice(resumeEnd)).replace(resumeCell, '') }

const skill = fs.readFileSync(path.join(root, 'SKILL.md'), 'utf8')
const start = skill.indexOf('\n## Config\n')
const end = skill.indexOf('\n## Environment\n')
if (start < 0 || end < start) throw new Error('SKILL.md needs a "## Config" section followed by "## Environment"')
const section = skill.slice(start + 1, end).trim()
// "### Detail pages" up to the next heading of its level or above: kept apart, so a host without detail pages
// gets the config grammar it had before them.
const detailStart = section.indexOf('\n### Detail pages\n')
if (detailStart < 0) throw new Error('SKILL.md\'s "## Config" section needs a "### Detail pages" subsection')
const after = section.slice(detailStart + 1).search(/\n#{2,3} /)
if (after < 0) throw new Error('"### Detail pages" must be followed by another heading inside "## Config"')
const detailEnd = detailStart + 1 + after
const detail = section.slice(detailStart + 1, detailEnd).trim()
let config = section.slice(0, detailStart + 1) + section.slice(detailEnd + 1)
// List stop reasons only collect.mjs's own process writes: `running` (a summary saved mid-run) and `interrupted` (a
// signal). A host that runs the collector in-process never gets them, and their wording (Ctrl-C, SIGHUP) would
// mislead its agent, so SKILL_CONFIG leaves them out; SKILL.md keeps them for the CLI.
for (const reason of ['running', 'interrupted']) {
  const entry = new RegExp(` \u00b7 \`${reason}\` \\([^()]*\\)`, 'g')
  const found = config.match(entry)?.length ?? 0
  if (found !== 1) throw new Error(`SKILL.md's "## Stop reasons" must list \`${reason}\` once, as " · \`${reason}\` (…)" (found ${found})`)
  config = config.replace(entry, '')
}

const out = [
  '// Generated by scripts/sync-references.mjs from references/*.md and SKILL.md — do not edit by hand.',
  `export const REFERENCES = {\n${entriesOf(notes).join('\n')}\n}`,
  `export const REFERENCES_HOST = {\n${entriesOf(hostNotes).join('\n')}\n}`,
  `export const SKILL_CONFIG = ${JSON.stringify(config)}`,
  `export const SKILL_CONFIG_DETAIL = ${JSON.stringify(detail)}`,
  '',
].join('\n')
fs.writeFileSync(path.join(dir, 'index.mjs'), out)
console.log(`references/index.mjs: ${names.length} references + SKILL_CONFIG (${config.length} chars) + SKILL_CONFIG_DETAIL (${detail.length} chars)`)
