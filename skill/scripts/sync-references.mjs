#!/usr/bin/env node
// Write references/index.mjs from references/*.md and SKILL.md, so hosts without a file system (the
// backend on Cloudflare) can serve the same text: REFERENCES (each note by name), SKILL_CONFIG
// (SKILL.md from "## Config" up to "## Environment" — the config grammar, which does not depend on
// how the scripts are run — without its "### Detail pages" subsection) and SKILL_CONFIG_DETAIL (that
// subsection, for hosts that offer detail pages). Run after editing either; a test checks they match.
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..')
const dir = path.join(root, 'references')
const names = fs
  .readdirSync(dir)
  .filter(f => f.endsWith('.md'))
  .sort()
const entries = names.map(f => `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))},`)

const skill = fs.readFileSync(path.join(root, 'SKILL.md'), 'utf8')
const start = skill.indexOf('\n## Config\n')
const end = skill.indexOf('\n## Environment\n')
if (start < 0 || end < start) throw new Error('SKILL.md needs a "## Config" section followed by "## Environment"')
const section = skill.slice(start + 1, end).trim()
// "### Detail pages" up to the next heading of its level or above: kept apart, so a host without detail pages
// gets the config grammar it had before them.
const detailStart = section.indexOf('\n### Detail pages\n')
if (detailStart < 0) throw new Error('SKILL.md\'s "## Config" section needs a "### Detail pages" subsection')
const after = section.slice(detailStart + 1).search(/\n#{2,3} /)
if (after < 0) throw new Error('"### Detail pages" must be followed by another heading inside "## Config"')
const detailEnd = detailStart + 1 + after
const detail = section.slice(detailStart + 1, detailEnd).trim()
const config = section.slice(0, detailStart + 1) + section.slice(detailEnd + 1)

const out = [
  '// Generated by scripts/sync-references.mjs from references/*.md and SKILL.md — do not edit by hand.',
  `export const REFERENCES = {\n${entries.join('\n')}\n}`,
  `export const SKILL_CONFIG = ${JSON.stringify(config)}`,
  `export const SKILL_CONFIG_DETAIL = ${JSON.stringify(detail)}`,
  '',
].join('\n')
fs.writeFileSync(path.join(dir, 'index.mjs'), out)
console.log(`references/index.mjs: ${names.length} references + SKILL_CONFIG (${config.length} chars) + SKILL_CONFIG_DETAIL (${detail.length} chars)`)
